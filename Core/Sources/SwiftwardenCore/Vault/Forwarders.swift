import Foundation

public enum Forwarder: String, CaseIterable, Codable, Sendable {
    case addy, simpleLogin, duckDuckGo, firefoxRelay, forwardEmail

    public var label: String {
        switch self {
        case .addy: "addy.io"
        case .simpleLogin: "SimpleLogin"
        case .duckDuckGo: "DuckDuckGo"
        case .firefoxRelay: "Firefox Relay"
        case .forwardEmail: "Forward Email"
        }
    }

    public var needsDomain: Bool { self == .addy || self == .forwardEmail }

    public func generate(apiKey: String, domain: String, website: String?) async throws -> String {
        let desc = "Generated by Swiftwarden" + (website.map { " for \($0)" } ?? "")
        var req: URLRequest
        func json(_ o: [String: Any]) throws -> Data { try JSONSerialization.data(withJSONObject: o) }
        switch self {
        case .addy:
            req = URLRequest(url: URL(string: "https://app.addy.io/api/v1/aliases")!)
            req.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
            req.httpBody = try json(["domain": domain, "description": desc])
        case .simpleLogin:
            var c = URLComponents(string: "https://app.simplelogin.io/api/alias/random/new")!
            if let website { c.queryItems = [URLQueryItem(name: "hostname", value: website)] }
            req = URLRequest(url: c.url!)
            req.setValue(apiKey, forHTTPHeaderField: "Authentication")
            req.httpBody = try json(["note": desc])
        case .duckDuckGo:
            req = URLRequest(url: URL(string: "https://quack.duckduckgo.com/api/email/addresses")!)
            req.setValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        case .firefoxRelay:
            req = URLRequest(url: URL(string: "https://relay.firefox.com/api/v1/relayaddresses/")!)
            req.setValue("Token \(apiKey)", forHTTPHeaderField: "Authorization")
            req.httpBody = try json(["enabled": true, "generated_for": website ?? "", "description": desc])
        case .forwardEmail:
            req = URLRequest(url: URL(string: "https://api.forwardemail.net/v1/domains/\(domain)/aliases")!)
            req.setValue("Basic " + Data("\(apiKey):".utf8).base64EncodedString(), forHTTPHeaderField: "Authorization")
            req.httpBody = try json(["labels": website ?? "", "description": desc])
        }
        req.httpMethod = "POST"
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        req.setValue("application/json", forHTTPHeaderField: "Accept")
        let (d, r) = try await URLSession.shared.data(for: req)
        guard let code = (r as? HTTPURLResponse)?.statusCode, (200 ..< 300).contains(code) else {
            throw APIError.http((r as? HTTPURLResponse)?.statusCode ?? 0, "\(label): " + (String(data: d.prefix(200), encoding: .utf8) ?? ""))
        }
        let o = (try? JSONSerialization.jsonObject(with: d)) as? [String: Any] ?? [:]
        switch self {
        case .addy: if let e = (o["data"] as? [String: Any])?["email"] as? String { return e }
        case .simpleLogin: if let e = o["alias"] as? String { return e }
        case .duckDuckGo: if let a = o["address"] as? String { return a + "@duck.com" }
        case .firefoxRelay: if let e = o["full_address"] as? String { return e }
        case .forwardEmail:
            if let n = o["name"] as? String { return n + "@" + ((o["domain"] as? [String: Any])?["name"] as? String ?? domain) }
        }
        throw APIError.invalidResponse
    }
}
